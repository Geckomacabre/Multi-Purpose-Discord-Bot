function escHtml(str: string): string {
  return str.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}

// ─── Ticket kinds ─────────────────────────────────────────────────────────────

/** 'support' is a normal help ticket; 'application' is a staff application reviewed by the apply role. */
export type TicketKind = 'support' | 'application';

export function ticketKind(ticket: Pick<ITicket, 'kind'> | null | undefined): TicketKind {
  return ticket?.kind === 'application' ? 'application' : 'support';
}

/** The role that gets access to (and is pinged in) a ticket of this kind. Applications fall back to the support role. */
export function ticketRoleId(cfg: ITicketConfig | null, kind: TicketKind): string | null {
  if (kind === 'application') return cfg?.apply_role_id ?? cfg?.support_role_id ?? null;
  return cfg?.support_role_id ?? null;
}

/** The category a ticket channel of this kind is created in. Applications fall back to the ticket category. */
export function ticketCategoryId(cfg: ITicketConfig | null, kind: TicketKind): string | null {
  if (kind === 'application') return cfg?.apply_category_id ?? cfg?.category_id ?? null;
  return cfg?.category_id ?? null;
}

/** Channel name prefix: ticket-12 or application-12 (one shared counter). */
export function ticketChannelName(kind: TicketKind, ticketNum: number): string {
  return `${kind === 'application' ? 'application' : 'ticket'}-${ticketNum}`;
}

// ─── Staff applications ───────────────────────────────────────────────────────

export const APPLICATION_TOPIC = 'Staff Application';


export async function fetchAllMessages(channel: TextChannel): Promise<Message[]> {
  const all: Message[] = [];
  let before: string | undefined;
  while (true) {
    const batch = await channel.messages.fetch({ limit: 100, before });
    if (!batch.size) break;
    all.push(...batch.values());
    before = batch.last()!.id;
    if (batch.size < 100) break;
  }
  return all.sort((a, b) => a.createdTimestamp - b.createdTimestamp);
}

const STARS: Record<number, string> = { 1: '⭐', 2: '⭐⭐', 3: '⭐⭐⭐', 4: '⭐⭐⭐⭐', 5: '⭐⭐⭐⭐⭐' };

function buildTranscriptText(ticket: ITicket, messages: Message[], claimerName?: string): string {
  const isApplication = ticketKind(ticket) === 'application';
  const lines: string[] = [
    `═══════════════════════════════════════`,
    isApplication ? `  📋 Staff Application #${ticket.ticket_num} Transcript` : `  🎫 Ticket #${ticket.ticket_num} Transcript`,
    `═══════════════════════════════════════`,
    `Topic    : ${ticket.topic ?? 'No topic'}`,
    `Opened by: ${ticket.user_id}`,
  ];
  if (claimerName) lines.push(`Claimed by: ${claimerName}`);
  lines.push(`Created  : ${new Date((ticket as any).created_at ?? Date.now()).toUTCString()}`);
  if (ticket.rating) lines.push(`Rating   : ${'⭐'.repeat(ticket.rating)} (${ticket.rating}/5)`);
  lines.push(`Messages : ${messages.length}`, `═══════════════════════════════════════`, '');

  for (const m of messages) {
    const time = new Date(m.createdTimestamp).toLocaleString('en-US', { dateStyle: 'short', timeStyle: 'short' });
    const tag = m.author.bot ? ' [BOT]' : '';
    lines.push(`[${time}] ${m.author.username}${tag}`);
    if (m.content) lines.push(m.content);
    for (const a of m.attachments.values()) lines.push(`📎 ${a.url}`);
    for (const e of m.embeds) {
      if (e.description) lines.push(`[Embed] ${e.description.slice(0, 200)}`);
      // Application answers live in embed fields; keep them whole so the log holds the full form.
      for (const f of e.fields) lines.push(`  ${f.name}: ${f.value.replace(/```/g, '').trim()}`);
    }
    lines.push('');
  }

  lines.push(`═══════════════════════════════════════`);
  lines.push(`Generated by TMCBot • ${new Date().toUTCString()}`);
  return lines.join('\n');
}

export function buildTranscriptFile(ticket: ITicket, messages: Message[], claimerName?: string): AttachmentBuilder {
  const text = buildTranscriptText(ticket, messages, claimerName);
  return new AttachmentBuilder(Buffer.from(text), { name: `${ticketChannelName(ticketKind(ticket), ticket.ticket_num)}-transcript.txt` });
}

export async function archiveTicket(
  channel: TextChannel,
  ticket: ITicket,
  cfg: ITicketConfig | null,
  bot: Client,
): Promise<void> {
  // Fetch messages and generate transcript
  const messages = await fetchAllMessages(channel);

  let claimerName: string | undefined;
  if (ticket.claimed_by) {
    const claimer = await bot.users.fetch(ticket.claimed_by).catch(() => null);
    claimerName = claimer?.username;
  }

  const file = buildTranscriptFile(ticket, messages, claimerName);
  const isApplication = ticketKind(ticket) === 'application';

  // Post transcript to log channel
  if (cfg?.log_channel_id) {
    try {
      const logCh = await bot.channels.fetch(cfg.log_channel_id) as TextChannel;
      const ratingText = ticket.rating ? ` • Rating: ${STARS[ticket.rating]}` : '';
      const claimerText = claimerName ? ` • ${isApplication ? 'Reviewed by' : 'Claimed by'}: ${claimerName}` : '';
      const label = isApplication ? `**Staff Application #${ticket.ticket_num}**` : `**Ticket #${ticket.ticket_num}** closed — <@${ticket.user_id}> — **Topic:** ${ticket.topic ?? 'None'}`;
      await logCh.send({
        content: `📋 ${label}${isApplication ? ` closed — applicant <@${ticket.user_id}>` : ''}${claimerText}${ratingText}`,
        files: [file],
      });
    } catch {}
  }

  // Applications don't get a "rate your support" prompt: tell the applicant it's closed and delete.
  if (isApplication) {
    try {
      const embed = new EmbedBuilder()
        .setColor(0x5865F2)
        .setTitle('🔒 Application Closed')
        .setDescription('Thanks for applying. This application has been closed by the team.\n\n*This channel will be deleted in 2 minutes.*');
      await channel.send({ content: `<@${ticket.user_id}>`, embeds: [embed] });
    } catch {}
    setTimeout(() => channel.delete().catch(() => {}), 2 * 60 * 1000);
    return;
  }

  // Post rating panel in the ticket channel before it gets deleted
  try {
    const helperText = claimerName
      ? `How was your experience with **${claimerName}**?`
      : 'How was your support experience?';
    const ratingRow = new ActionRowBuilder<ButtonBuilder>().addComponents(
      ...[1, 2, 3, 4, 5].map(n =>
        new ButtonBuilder()
          .setCustomId(`ticket:rate:${n}:${channel.id}`)
          .setLabel(`${n} ⭐`)
          .setStyle(ButtonStyle.Secondary)
      )
    );
    const embed = new EmbedBuilder()
      .setColor(0x5865F2)
      .setTitle('🔒 Ticket Closed')
      .setDescription(`${helperText}\n\n*This channel will be deleted in 2 minutes.*`);
    await channel.send({ content: `<@${ticket.user_id}>`, embeds: [embed], components: [ratingRow] });
  } catch {}

  // Delete channel after 2 minutes
  setTimeout(() => channel.delete().catch(() => {}), 2 * 60 * 1000);
}

// ─── "Not a support channel" message (/ticket redirect, /support) ─────────────

export type RedirectTarget = { id: string; label: string };

/**
 * The targets for this server: the ones set with /ticket config redirect-add, else the
 * bot-wide env list (TICKET_REDIRECT_CHANNELS) filtered to channels that exist in THIS
 * server, so another server's IDs never turn into dead links.
 */
export function resolveRedirectTargets(guild: Guild, configured: RedirectTarget[], envList: RedirectTarget[]): RedirectTarget[] {
  const list = configured.length ? configured : envList;
  return list.filter(t => guild.channels.cache.has(t.id)).slice(0, 5);
}

/**
 * The message itself, unchanged from the original when there are channel links. A server with
 * no links gets the same embed with an Open a Ticket button instead of a dead end.
 */
export function buildRedirectMessage(guild: Guild, targets: RedirectTarget[], botAvatar?: string) {
  const embed = new EmbedBuilder()
    .setColor(0x5865F2)
    .setTitle('Hello there!')
    .setDescription(
      `🔴 This channel is not intended for support queries. All support-related matters should be discussed within the appropriate support channels.

` +
      (targets.length
        ? `🟡 Please use the buttons below to navigate to the relevant support channel.`
        : `🟡 Please open a ticket with the button below and a staff member will assist you there.`)
    )
    .setFooter({ text: `Sent by ${guild.members.me?.displayName ?? 'the bot'}`, iconURL: botAvatar });
  const row = new ActionRowBuilder<ButtonBuilder>().addComponents(
    targets.length
      ? targets.map(({ id, label }) => new ButtonBuilder().setLabel(label.slice(0, 80)).setStyle(ButtonStyle.Link).setURL(`https://discord.com/channels/${guild.id}/${id}`))
      : [new ButtonBuilder().setCustomId('ticket:open').setLabel('Open a Ticket').setStyle(ButtonStyle.Primary).setEmoji('🎫')],
  );
  return { embeds: [embed], components: [row] };
}

export function buildModPanel(channelId: string): ActionRowBuilder<ButtonBuilder>[] {
  const row1 = new ActionRowBuilder<ButtonBuilder>().addComponents(
    new ButtonBuilder().setCustomId(`ticket:claim:${channelId}`).setLabel('🙋 Claim').setStyle(ButtonStyle.Primary),
  );
  const row2 = new ActionRowBuilder<ButtonBuilder>().addComponents(
    new ButtonBuilder().setCustomId(`ticket:save:${channelId}`).setLabel('💾 Save Transcript').setStyle(ButtonStyle.Secondary),
    new ButtonBuilder().setCustomId(`ticket:close:${channelId}`).setLabel('🔒 Close').setStyle(ButtonStyle.Danger),
  );
  return [row1, row2];
}

// ─── Ticket permissions ───────────────────────────────────────────────────────

type TicketInteraction = ButtonInteraction | ChatInputCommandInteraction;

/** Server admins. `has()` resolves Administrator implicitly, so Manage Server covers both. */
export function isTicketAdmin(interaction: TicketInteraction): boolean {
  return interaction.memberPermissions?.has(PermissionFlagsBits.ManageGuild) ?? false;
}

function memberRoleIds(interaction: TicketInteraction): string[] {
  const member: any = interaction.member;
  if (!member) return [];
  if (Array.isArray(member.roles)) return member.roles;
  return [...(member.roles?.cache?.keys() ?? [])];
}

/**
 * Admins, the role for this ticket's kind (support role, or the apply role for a staff application),
 * or anyone with Manage Messages when no role is set.
 */
export function isTicketStaff(interaction: TicketInteraction, cfg: ITicketConfig | null, ticket?: Pick<ITicket, 'kind'> | null): boolean {
  if (isTicketAdmin(interaction)) return true;
  const roleId = ticketRoleId(cfg, ticketKind(ticket));
  if (roleId) return memberRoleIds(interaction).includes(roleId);
  return interaction.memberPermissions?.has(PermissionFlagsBits.ManageMessages) ?? false;
}

export type TicketPermCheck = { allowed: true } | { allowed: false; reason: string };

/**
 * Only admins and the staff member who claimed the ticket may close it.
 * The person who opened the ticket never can, even if they otherwise qualify.
 */
export function canCloseTicket(interaction: TicketInteraction, ticket: ITicket): TicketPermCheck {
  if (ticket.user_id === interaction.user.id) {
    return {
      allowed: false,
      reason: '❌ You opened this ticket, so you can\'t close it. A staff member who claims it — or an admin — will close it for you.',
    };
  }
  if (isTicketAdmin(interaction)) return { allowed: true };
  if (ticket.claimed_by && ticket.claimed_by === interaction.user.id) return { allowed: true };
  return { allowed: false, reason: '❌ Only an admin or the staff member who claimed this ticket can close it.' };
}
