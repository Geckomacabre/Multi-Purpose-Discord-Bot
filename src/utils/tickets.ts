import {
  ActionRowBuilder, AttachmentBuilder, ButtonBuilder, ButtonStyle,
  Client, EmbedBuilder, Message, TextChannel,
} from 'discord.js';
import type { ITicket, ITicketConfig } from './db';

function escHtml(str: string): string {
  return str.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}

export async function fetchAllMessages(channel: TextChannel): Promise<Message[]> {
  const all: Message[] = [];
  let before: string | undefined;
  while (true) {
    const batch = await channel.messages.fetch({ limit: 100, before });
    if (!batch.size) break;
    all.push(...batch.values());
    before = batch.last()!.id;
    if (batch.size < 100) break;
  }
  return all.sort((a, b) => a.createdTimestamp - b.createdTimestamp);
}

const STARS: Record<number, string> = { 1: '⭐', 2: '⭐⭐', 3: '⭐⭐⭐', 4: '⭐⭐⭐⭐', 5: '⭐⭐⭐⭐⭐' };

function buildTranscriptText(ticket: ITicket, messages: Message[], claimerName?: string): string {
  const lines: string[] = [
    `═══════════════════════════════════════`,
    `  🎫 Ticket #${ticket.ticket_num} Transcript`,
    `═══════════════════════════════════════`,
    `Topic    : ${ticket.topic ?? 'No topic'}`,
    `Opened by: ${ticket.user_id}`,
  ];
  if (claimerName) lines.push(`Claimed by: ${claimerName}`);
  lines.push(`Created  : ${new Date((ticket as any).created_at ?? Date.now()).toUTCString()}`);
  if (ticket.rating) lines.push(`Rating   : ${'⭐'.repeat(ticket.rating)} (${ticket.rating}/5)`);
  lines.push(`Messages : ${messages.length}`, `═══════════════════════════════════════`, '');

  for (const m of messages) {
    const time = new Date(m.createdTimestamp).toLocaleString('en-US', { dateStyle: 'short', timeStyle: 'short' });
    const tag = m.author.bot ? ' [BOT]' : '';
    lines.push(`[${time}] ${m.author.username}${tag}`);
    if (m.content) lines.push(m.content);
    for (const a of m.attachments.values()) lines.push(`📎 ${a.url}`);
    for (const e of m.embeds) if (e.description) lines.push(`[Embed] ${e.description.slice(0, 200)}`);
    lines.push('');
  }

  lines.push(`═══════════════════════════════════════`);
  lines.push(`Generated by TMCBot • ${new Date().toUTCString()}`);
  return lines.join('\n');
}

export function buildTranscriptFile(ticket: ITicket, messages: Message[], claimerName?: string): AttachmentBuilder {
  const text = buildTranscriptText(ticket, messages, claimerName);
  return new AttachmentBuilder(Buffer.from(text), { name: `ticket-${ticket.ticket_num}-transcript.txt` });
}

export async function archiveTicket(
  channel: TextChannel,
  ticket: ITicket,
  cfg: ITicketConfig | null,
  bot: Client,
): Promise<void> {
  // Fetch messages and generate transcript
  const messages = await fetchAllMessages(channel);

  let claimerName: string | undefined;
  if (ticket.claimed_by) {
    const claimer = await bot.users.fetch(ticket.claimed_by).catch(() => null);
    claimerName = claimer?.username;
  }

  const file = buildTranscriptFile(ticket, messages, claimerName);

  // Post transcript to log channel
  if (cfg?.log_channel_id) {
    try {
      const logCh = await bot.channels.fetch(cfg.log_channel_id) as TextChannel;
      const ratingText = ticket.rating ? ` • Rating: ${STARS[ticket.rating]}` : '';
      const claimerText = claimerName ? ` • Claimed by: ${claimerName}` : '';
      await logCh.send({
        content: `📋 **Ticket #${ticket.ticket_num}** closed — <@${ticket.user_id}> — **Topic:** ${ticket.topic ?? 'None'}${claimerText}${ratingText}`,
        files: [file],
      });
    } catch {}
  }

  // DM user with rating panel before deleting channel
  try {
    const user = await bot.users.fetch(ticket.user_id);
    const helperText = claimerName
      ? `How was your experience with **${claimerName}**?`
      : 'How was your support experience?';
    const ratingRow = new ActionRowBuilder<ButtonBuilder>().addComponents(
      ...[1, 2, 3, 4, 5].map(n =>
        new ButtonBuilder()
          .setCustomId(`ticket:rate:${n}:${channel.id}`)
          .setLabel(`${n} ⭐`)
          .setStyle(ButtonStyle.Secondary)
      )
    );
    const embed = new EmbedBuilder()
      .setColor(0x5865F2)
      .setTitle(`🎫 Ticket #${ticket.ticket_num} Closed`)
      .setDescription(`${helperText}\n*Your feedback helps us improve!*`);
    await user.send({ embeds: [embed], components: [ratingRow] });
  } catch {}

  // Delete channel after short delay
  setTimeout(() => channel.delete().catch(() => {}), 5000);
}

export function buildModPanel(channelId: string): ActionRowBuilder<ButtonBuilder>[] {
  const row1 = new ActionRowBuilder<ButtonBuilder>().addComponents(
    new ButtonBuilder().setCustomId(`ticket:claim:${channelId}`).setLabel('🙋 Claim').setStyle(ButtonStyle.Primary),
  );
  const row2 = new ActionRowBuilder<ButtonBuilder>().addComponents(
    new ButtonBuilder().setCustomId(`ticket:save:${channelId}`).setLabel('💾 Save Transcript').setStyle(ButtonStyle.Secondary),
    new ButtonBuilder().setCustomId(`ticket:close:${channelId}`).setLabel('🔒 Close').setStyle(ButtonStyle.Danger),
  );
  return [row1, row2];
}
