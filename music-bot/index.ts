import { Client, GatewayIntentBits, REST, Routes, Events, MessageFlags } from 'discord.js';
import { commands, handleButton } from './commands';
import { createManager, manager } from './lavalink';
import logger from './logger';

const TOKEN = Bun.env.TOKEN;
const CLIENT_ID = Bun.env.CLIENT_ID;
// The music commands are registered as GUILD commands in this server. That's
// required when sharing the main bot's application: the main bot replaces its
// GLOBAL commands on every startup, so global music commands would be wiped.
// Guild commands also show up instantly instead of taking up to an hour.
const GUILD_ID = Bun.env.GUILD_ID;
// Shared secret with the local Lavalink server (generated by lavalink/setup-lavalink.ps1).
const LAVALINK_PASSWORD = Bun.env.LAVALINK_PASSWORD;

if (!TOKEN || !CLIENT_ID) {
  logger.error('Missing TOKEN or CLIENT_ID in the environment (.env). See README.md.');
  process.exit(1);
}
if (!LAVALINK_PASSWORD) {
  logger.error('Missing LAVALINK_PASSWORD in .env. Run lavalink/setup-lavalink.ps1 (start.ps1 does this for you).');
  process.exit(1);
}
if (!GUILD_ID) {
  logger.warn('GUILD_ID is not set, so the music commands are registered globally. If this bot shares the main bot\'s token, '
    + 'the main bot will delete them on every restart (they come back within 5 minutes). Set GUILD_ID to avoid that.');
}

process.on('uncaughtException', (err) => logger.error(`Uncaught exception: ${err?.stack ?? err}`));
process.on('unhandledRejection', (reason: any) => logger.error(`Unhandled rejection: ${reason?.stack ?? reason}`));

// Only the intents music needs: guild info + voice states.
const client = new Client({
  intents: [GatewayIntentBits.Guilds, GatewayIntentBits.GuildVoiceStates],
});
createManager(client, LAVALINK_PASSWORD);

const rest = new REST({ version: '10' }).setToken(TOKEN);
const commandsRoute = GUILD_ID ? Routes.applicationGuildCommands(CLIENT_ID, GUILD_ID) : Routes.applicationCommands(CLIENT_ID);
const commandRoute = (id: string) => GUILD_ID ? Routes.applicationGuildCommand(CLIENT_ID, GUILD_ID, id) : Routes.applicationCommand(CLIENT_ID, id);
// Commands this bot used to register, removed when it starts.
const RETIRED_COMMANDS = ['music'];

type RegisteredCommand = { id: string; name: string };

// Each command is created or edited on its own. Never PUT: this bot can share its
// application with the main bot, and a PUT replaces every command in that scope.
// Existing commands are PATCHed rather than re-POSTed, because Discord limits
// command creates per day.
async function registerCommands() {
  const existing = await rest.get(commandsRoute) as RegisteredCommand[];
  for (const old of existing.filter((c) => RETIRED_COMMANDS.includes(c.name))) {
    await rest.delete(commandRoute(old.id));
    logger.info(`Removed the old /${old.name} command.`);
  }
  for (const cmd of commands.values()) {
    const body = cmd.data.toJSON();
    const found = existing.find((c) => c.name === body.name);
    if (found) await rest.patch(commandRoute(found.id), { body });
    else await rest.post(commandsRoute, { body });
  }
  logger.info(`Registered ${commands.size} music commands${GUILD_ID ? ` in guild ${GUILD_ID}` : ' globally'}.`);
}

// The main bot can remove these when it re-syncs its own commands, so check every
// few minutes and put back any that are gone (a GET is cheap; only POST when missing).
async function ensureCommands() {
  try {
    const existing = await rest.get(commandsRoute) as RegisteredCommand[];
    for (const cmd of commands.values()) {
      if (existing.some((c) => c.name === cmd.data.name)) continue;
      logger.warn(`/${cmd.data.name} was missing, re-registering it.`);
      await rest.post(commandsRoute, { body: cmd.data.toJSON() });
    }
  } catch (e) {
    logger.warn(`Command check failed: ${e}`);
  }
}

client.once(Events.ClientReady, async (c) => {
  logger.info(`Music bot logged in as ${c.user.tag}`);
  await manager.init({ id: c.user.id, username: c.user.username });
  try {
    await registerCommands();
  } catch (e) {
    logger.error(`Command registration failed: ${e}`);
  }
  setInterval(ensureCommands, 5 * 60 * 1000);
});

const replyError = async (interaction: any) => {
  const content = 'There was an error running that. Please try again.';
  if (interaction.deferred || interaction.replied) await interaction.followUp({ content, flags: MessageFlags.Ephemeral }).catch(() => {});
  else await interaction.reply({ content, flags: MessageFlags.Ephemeral }).catch(() => {});
};

// When sharing the main bot's token, both processes receive every interaction.
// Each one only answers its own: the main bot ignores commands it doesn't have
// and music:* buttons, and this bot ignores everything else.
client.on(Events.InteractionCreate, async (interaction) => {
  try {
    if (interaction.isAutocomplete()) {
      await commands.get(interaction.commandName)?.autocomplete?.(interaction);
      return;
    }
    if (interaction.isButton()) {
      if (interaction.customId.startsWith('music:')) await handleButton(interaction);
      return;
    }
    if (interaction.isChatInputCommand()) {
      await commands.get(interaction.commandName)?.run?.(interaction);
    }
  } catch (error: any) {
    logger.error(`Error handling ${interaction.isChatInputCommand() ? `/${interaction.commandName}` : 'interaction'}: ${error?.stack ?? error}`);
    if (interaction.isRepliable()) await replyError(interaction);
  }
});

// Leave voice channels cleanly instead of leaving a ghost bot behind.
async function shutdown(signal: string) {
  logger.info(`${signal} received, leaving voice channels and shutting down.`);
  await Promise.allSettled([...manager.players.values()].map((p) => p.destroy('Shutdown')));
  await client.destroy();
  process.exit(0);
}
process.once('SIGINT', () => shutdown('SIGINT'));
process.once('SIGTERM', () => shutdown('SIGTERM'));

client.login(TOKEN);
