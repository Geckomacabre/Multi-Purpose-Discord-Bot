# Prepares the local Lavalink server the music bot plays through. Safe to run any
# time (start.ps1 runs it on every start); it only does what's missing:
#  - downloads the pinned Lavalink and plugin jars from their official GitHub
#    releases and checks their SHA-256,
#  - generates a random LAVALINK_PASSWORD into ../.env if there isn't one,
#  - writes application.yml (gitignored, it contains the password).

$ErrorActionPreference = 'Stop'
$here = $PSScriptRoot
$envFile = Join-Path (Split-Path $here -Parent) '.env'

# Pinned versions. To upgrade, change the URL and paste the new release's SHA-256.
$jars = @(
    @{ Path = 'Lavalink.jar'
       Url  = 'https://github.com/lavalink-devs/Lavalink/releases/download/4.2.2/Lavalink.jar'
       Sha  = '8cb801e591072c3689fafd71ccf571a95a4ead3cc35dfc045e157d763d89119a' },
    @{ Path = 'plugins\youtube-plugin-1.18.2.jar'
       Url  = 'https://github.com/lavalink-devs/youtube-source/releases/download/1.18.2/youtube-plugin-1.18.2.jar'
       Sha  = 'dd4b3bce50dbc7582c80776bad47bad87bef1dc683c69d66ab4a084aa3006238' },
    @{ Path = 'plugins\sponsorblock-plugin-3.0.1.jar'
       Url  = 'https://github.com/topi314/Sponsorblock-Plugin/releases/download/3.0.1/sponsorblock-plugin-3.0.1.jar'
       Sha  = '7a79e78d91677dbb45c1d33f442a01343c28ce6ac8998a4dd6549809ab047bbd' }
)

New-Item -ItemType Directory -Force (Join-Path $here 'plugins'), (Join-Path $here 'logs') | Out-Null
[Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12

foreach ($jar in $jars) {
    $dest = Join-Path $here $jar.Path
    $ok = (Test-Path $dest) -and ((Get-FileHash $dest -Algorithm SHA256).Hash -eq $jar.Sha.ToUpper())
    if ($ok) { continue }
    Write-Host "Downloading $($jar.Url)"
    $tmp = "$dest.download"
    Invoke-WebRequest -Uri $jar.Url -OutFile $tmp -UseBasicParsing
    $hash = (Get-FileHash $tmp -Algorithm SHA256).Hash
    if ($hash -ne $jar.Sha.ToUpper()) {
        Remove-Item $tmp -Force
        throw "Checksum mismatch for $($jar.Path): got $hash"
    }
    Move-Item -Force $tmp $dest
}
# Remove plugin jars that aren't pinned above (old versions would load twice).
$pinned = $jars | ForEach-Object { Split-Path $_.Path -Leaf }
Get-ChildItem (Join-Path $here 'plugins') -Filter *.jar | Where-Object { $pinned -notcontains $_.Name } | Remove-Item -Force

# Shared secret between the bot and Lavalink. Lavalink only listens on 127.0.0.1,
# so this just stops other local programs from driving it.
if (-not (Test-Path $envFile)) { throw "Missing $envFile (copy .env.example first)" }
$line = Get-Content $envFile | Where-Object { $_ -match '^\s*LAVALINK_PASSWORD\s*=\s*\S' } | Select-Object -Last 1
if ($line) {
    $password = ($line -split '=', 2)[1].Trim().Trim('"', "'")
} else {
    $bytes = New-Object byte[] 32
    [Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($bytes)
    $password = ([BitConverter]::ToString($bytes) -replace '-', '').ToLower()
    $raw = Get-Content $envFile -Raw
    $prefix = if ($raw -and -not $raw.EndsWith("`n")) { "`r`n" } else { '' }
    Add-Content -Path $envFile -Value "$prefix# Generated by lavalink/setup-lavalink.ps1`r`nLAVALINK_PASSWORD=$password" -Encoding utf8
    Write-Host 'Generated a new LAVALINK_PASSWORD in .env'
}

$yml = Get-Content (Join-Path $here 'application.template.yml') -Raw
$yml = $yml.Replace('__LAVALINK_PASSWORD__', $password)
# UTF-8 without a BOM: Lavalink's YAML parser rejects a BOM.
[IO.File]::WriteAllText((Join-Path $here 'application.yml'), $yml, (New-Object Text.UTF8Encoding $false))
